"""Turn DeepSpec acceptance-eval output into the head-to-head table for BENCHMARKS.md.

Two paths:

  1. results.csv  -> markdown table        (deterministic; the authoritative, self-tested path)
  2. eval stdout  -> results.csv           (best-effort extraction; adjust the regex to your
                                            eval.py revision — see EVAL_LINE_RE below)

The CSV is the source of record for a run's numbers and is kept in sync with the head-to-head
table in BENCHMARKS.md. The raw eval logs (the evidence) live in the run's ``raw/`` directory.

Examples
--------
Render the table from an existing results.csv (what you normally want)::

    python scripts/parse_eval_results.py --csv benchmarks/<run>/results.csv

Rebuild results.csv from raw eval logs, then render::

    python scripts/parse_eval_results.py \\
        --dspark-log benchmarks/<run>/raw/eval.dspark.log \\
        --eagle3-log benchmarks/<run>/raw/eval.eagle3.log \\
        --write-csv benchmarks/<run>/results.csv

Verify the renderer against the known committed numbers::

    python scripts/parse_eval_results.py --selftest

This script uses only the Python standard library. Run it with ``-I`` if the logs it reads are
untrusted (``python -I scripts/parse_eval_results.py ...``).
"""
from __future__ import annotations

import argparse
import csv
import io
import re
import sys
from pathlib import Path

# Canonical task order for the DeepSpec acceptance eval (keeps the table stable).
TASK_ORDER = [
    "gsm8k", "math500", "aime25", "humaneval", "mbpp",
    "livecodebench", "mt-bench", "alpaca", "arena-hard-v2",
]

# Best-effort extraction from eval stdout. DeepSpec's eval.py output format varies by revision,
# so this is intentionally loose: it looks for a known task name on a line that also carries a
# "mean accepted length" style float. ADJUST THIS to match the exact lines your eval.py emits
# (print a couple of lines from your log and tweak the alternation/keywords below). The CSV path
# does not depend on this regex.
_TASKS_ALT = "|".join(re.escape(t) for t in TASK_ORDER)
EVAL_LINE_RE = re.compile(
    r"(?P<task>" + _TASKS_ALT + r")\b"
    r".*?"
    r"(?:accept(?:ed)?[_ ]?len(?:gth)?|mean[_ ]?accept(?:ed)?[_ ]?len(?:gth)?|tau)\s*[=:]\s*"
    r"(?P<val>\d+(?:\.\d+)?)",
    re.IGNORECASE,
)


def parse_eval_log(text: str) -> dict[str, float]:
    """Extract {task: mean_accepted_length} from one eval stdout blob. Last match per task wins."""
    out: dict[str, float] = {}
    for m in EVAL_LINE_RE.finditer(text):
        out[m.group("task").lower()] = float(m.group("val"))
    return out


def load_csv(path: Path) -> list[dict]:
    rows: list[dict] = []
    with path.open(newline="") as fh:
        reader = csv.DictReader(r for r in fh if not r.lstrip().startswith("#"))
        for r in reader:
            rows.append({
                "task": r["task"].strip(),
                "dspark": float(r["dspark_accepted_len"]),
                "eagle3": float(r["eagle3_accepted_len"]),
            })
    return _order(rows)


def rows_from_logs(dspark: dict[str, float], eagle3: dict[str, float]) -> list[dict]:
    tasks = [t for t in TASK_ORDER if t in dspark or t in eagle3]
    rows = [{"task": t, "dspark": dspark.get(t, float("nan")),
             "eagle3": eagle3.get(t, float("nan"))} for t in tasks]
    if not rows:
        raise SystemExit(
            "No known task metrics found in the logs. The EVAL_LINE_RE regex almost certainly "
            "needs adjusting to your eval.py output — see the note next to it in this file."
        )
    return _order(rows)


def _order(rows: list[dict]) -> list[dict]:
    idx = {t: i for i, t in enumerate(TASK_ORDER)}
    return sorted(rows, key=lambda r: idx.get(r["task"], len(TASK_ORDER)))


def _fmt(x: float) -> str:
    return "nan" if x != x else f"{x:g}"


def write_csv(rows: list[dict], path: Path) -> None:
    with path.open("w", newline="") as fh:
        fh.write("# Regenerated by scripts/parse_eval_results.py from raw eval logs.\n")
        fh.write("task,dspark_accepted_len,eagle3_accepted_len,dspark_advantage\n")
        for r in rows:
            adv = r["dspark"] - r["eagle3"]
            fh.write(f"{r['task']},{_fmt(r['dspark'])},{_fmt(r['eagle3'])},{_fmt(round(adv, 3))}\n")


def render_markdown(rows: list[dict]) -> str:
    buf = io.StringIO()
    buf.write("| Task | DSpark | EAGLE-3 | DSpark advantage |\n")
    buf.write("|---|---|---|---|\n")
    ds_vals, e3_vals = [], []
    for r in rows:
        ds, e3 = r["dspark"], r["eagle3"]
        adv = ds - e3
        winner = f"**{_fmt(ds)}**" if (ds == ds and e3 == e3 and ds >= e3) else _fmt(ds)
        buf.write(f"| {r['task']} | {winner} | {_fmt(e3)} | {'+' if adv >= 0 else ''}{_fmt(round(adv, 3))} |\n")
        if ds == ds:
            ds_vals.append(ds)
        if e3 == e3:
            e3_vals.append(e3)
    if ds_vals and e3_vals:
        ds_mean = sum(ds_vals) / len(ds_vals)
        e3_mean = sum(e3_vals) / len(e3_vals)
        adv = ds_mean - e3_mean
        pct = 100 * adv / e3_mean if e3_mean else float("nan")
        buf.write(
            f"| **mean** | **≈{ds_mean:.3f}** | **≈{e3_mean:.3f}** | "
            f"**+{adv:.3f} (~{pct:.0f}%)** |\n"
        )
    return buf.getvalue()


# Known committed numbers (BENCHMARKS.md, 2026-11-16 proof run) — the renderer self-test target.
_SELFTEST_ROWS = [
    {"task": "gsm8k", "dspark": 1.247, "eagle3": 1.140},
    {"task": "math500", "dspark": 1.251, "eagle3": 1.143},
    {"task": "aime25", "dspark": 1.238, "eagle3": 1.131},
    {"task": "humaneval", "dspark": 1.237, "eagle3": 1.147},
    {"task": "mbpp", "dspark": 1.24, "eagle3": 1.171},
    {"task": "livecodebench", "dspark": 1.24, "eagle3": 1.128},
    {"task": "mt-bench", "dspark": 1.26, "eagle3": 1.161},
    {"task": "alpaca", "dspark": 1.24, "eagle3": 1.169},
    {"task": "arena-hard-v2", "dspark": 1.25, "eagle3": 1.123},
]


def selftest() -> int:
    md = render_markdown(_SELFTEST_ROWS)
    checks = {
        "DSpark wins gsm8k (bolded)": "| gsm8k | **1.247** | 1.14 | +0.107 |" in md,
        "mean row rendered": "**mean**" in md and "~9%" in md,
        "advantage sign shown": "+0.108" in md,  # math500
    }
    ok = all(checks.values())
    for name, passed in checks.items():
        print(f"  [{'ok' if passed else 'FAIL'}] {name}")
    print(md)
    print("SELFTEST:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--csv", type=Path, help="results.csv to render into a markdown table")
    ap.add_argument("--dspark-log", type=Path, help="raw eval stdout for the DSpark draft")
    ap.add_argument("--eagle3-log", type=Path, help="raw eval stdout for the EAGLE-3 draft")
    ap.add_argument("--write-csv", type=Path, help="write extracted rows to this results.csv")
    ap.add_argument("--selftest", action="store_true", help="verify the renderer against known numbers")
    args = ap.parse_args(argv)

    if args.selftest:
        return selftest()

    if args.csv:
        rows = load_csv(args.csv)
    elif args.dspark_log or args.eagle3_log:
        ds = parse_eval_log(args.dspark_log.read_text()) if args.dspark_log else {}
        e3 = parse_eval_log(args.eagle3_log.read_text()) if args.eagle3_log else {}
        rows = rows_from_logs(ds, e3)
        if args.write_csv:
            write_csv(rows, args.write_csv)
            print(f"wrote {args.write_csv}", file=sys.stderr)
    else:
        ap.error("give --csv, or --dspark-log/--eagle3-log, or --selftest")

    sys.stdout.write(render_markdown(rows))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
